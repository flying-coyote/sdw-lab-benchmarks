def main():
    for r in R:
        assert set(r) == set(COLS), (r["row_id"], set(COLS) ^ set(r))
    out_csv = HERE / "vocabulary-table.csv"
    with out_csv.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLS)
        w.writeheader()
        w.writerows(R)

    counts = collections.Counter((r["direction"], r["grade"]) for r in R)
    md = ["# D3FEND AI artifacts and OCSF ai_* objects: shared vocabulary (R8)", "",
          "Generated by `build_table.py` from the rows graded under `METHOD.md`. Pins: OCSF v1.9.0, "
          "OCSF main d1cbd619 (1.10.0-dev), OCSF PR #1754 head 08d6f530, D3FEND develop 048c6936, "
          "D3FEND PR #601 head 87f09c71.", "",
          "| Row | Term | D3FEND status / parent | Kind | OCSF counterpart | Grade | 1.9.0 | main | #1754 | Gap, OCSF side | Gap, D3FEND side | Proposed link |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in R:
        cells = [r["row_id"], r["term"], f'{r["d3fend_status"]}; {r["d3fend_parent_or_counterpart"]}',
                 r["kind"], r["ocsf_counterpart"], f'**{r["grade"]}**', r["ocsf_1_9_0"],
                 r["ocsf_main_1_10_dev"], r["ocsf_pr1754_draft"], r["gap_ocsf_side"],
                 r["gap_d3fend_side"], r["proposed_link"]]
        md.append("| " + " | ".join(c.replace("|", "/") for c in cells) + " |")
    md += ["", "## Grade counts", "", "| Direction | exact | partial | wrong-kind | none |", "|---|---:|---:|---:|---:|"]
    for d in ("D3FEND->OCSF", "OCSF->D3FEND"):
        md.append(f"| {d} | " + " | ".join(str(counts[(d, g)]) for g in ("exact", "partial", "wrong-kind", "none")) + " |")
    (HERE / "vocabulary-table.md").write_text("\n".join(md) + "\n")
    for k, v in sorted(counts.items()):
        print(k, v)


if __name__ == "__main__":
    main()
