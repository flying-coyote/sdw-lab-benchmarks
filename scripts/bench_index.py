#!/usr/bin/env python3
"""Generate the bench index table in README.md from each bench folder's bench.yaml.

Standard library only. Reads every top-level ``*/bench.yaml`` (a flat ``key: value``
file, contract in docs/BENCH-LAYOUT.md), groups the benches by ``cluster``, and
rewrites the block between the two marker comments in README.md. Nothing outside
that block changes, and no file inside a bench folder is ever written.

    python3 scripts/bench_index.py            # rewrite the index in README.md
    python3 scripts/bench_index.py --check    # exit 1 if README.md is out of date
    python3 scripts/bench_index.py --strict   # also fail on bench.yaml contract problems

Exit codes: 0 written (or up to date), 1 row count differs from --expect or --check
found drift, 2 README markers missing, 3 contract problems under --strict.
The output is a pure function of the bench.yaml files and the folder names, with
no timestamps, so two consecutive runs leave README.md byte-identical.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"

START = "<!-- BENCH-INDEX:START (generated by scripts/bench_index.py from */bench.yaml; edit those, not this block) -->"
END = "<!-- BENCH-INDEX:END -->"

# Shared folders described by hand under the table, never indexed as benches.
SKIP = {"lib", "charts", "scripts", "workloads", "docs"}

# The frozen gate cannot receive a bench.yaml (every file in it is frozen), so its row is fixed here.
FROZEN = {
    "ontology-vs-schema-gate": {
        "name": "ontology-vs-schema-gate",
        "cluster": "mapping-and-models",
        "title": "Schema-only pipeline vs an ontology-backed gate on the 925-row OCSF crosswalk corpus (design frozen, nothing scored)",
        "status": "frozen-design",
        "tier": "B (design)",
        "claim_kind": "none",
        "prereg": "PREREGISTRATION.md; HARNESS-ADDENDUM.md",
        "results": "none",
    }
}

CLUSTERS = [
    ("detection", "Detection and the planted-chain testbed"),
    ("mapping-and-models", "Mapping, schema fidelity and model arms"),
    ("formats-and-lakehouse", "Formats, readers and lakehouse read/write paths"),
    ("catalogs-engines-cost", "Catalogs, engines, routing and cost"),
    ("ai-security", "AI security"),
]
CLUSTER_KEYS = {k for k, _ in CLUSTERS}
STATUSES = {"published", "first-pass", "scaffold", "spec", "foundation", "superseded", "frozen-design"}
CLAIM_KINDS = {"measured", "demonstration", "mixed", "none"}
VERDICTS = {"SOUND", "CAVEAT", "DEMONSTRATION", "CANNOT-FAIL", "DRIFTED", "SUPERSEDED", "SCAFFOLD"}
REQUIRED = ["name", "cluster", "title", "status", "tier", "claim_kind", "prereg", "results"]

NOT_DESCRIBED = "*not yet described (no valid `bench.yaml`)*"

# One spelling for a tier the bench's docs do not give; the variants below are folded into it.
TIER_UNSTATED = "not stated"
TIER_UNSTATED_PREFIXES = ("not stated", "unstated", "none")


def norm_tier(value):
    """Fold the unstated-tier spellings into TIER_UNSTATED, keeping any parenthetical annotation."""
    v = (value or "").strip()
    low = v.lower()
    if not v or not low.startswith(TIER_UNSTATED_PREFIXES):
        return v
    note = v[v.find("("):] if "(" in v else ""
    return f"{TIER_UNSTATED} {note}".strip()


def is_path(part):
    """A prereg/results entry is a path when it has no spaces and no parenthetical text."""
    return " " not in part and "(" not in part


def parse_yaml(path):
    """Parse the flat key: value contract. Values are taken verbatim after the first colon."""
    data = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, _, value = line.partition(":")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        data[key.strip()] = value
    return data


def cell(text):
    return str(text).replace("|", "&#124;").replace("\n", " ").strip()


def link_list(bench, value):
    """Render a '; '-separated list of paths as links relative to the repo root."""
    if not value or value.strip().lower() == "none":
        return "none"
    out = []
    for part in [p.strip() for p in value.split(";") if p.strip()]:
        if part.startswith(("http://", "https://")):
            out.append(f"[link]({part})")
        elif not is_path(part):
            out.append(cell(part))
        else:
            rel = part.removeprefix("./")
            if rel.startswith(bench + "/"):
                rel = rel[len(bench) + 1:]
            out.append(f"[{cell(rel)}]({bench}/{rel})")
    return ", ".join(out)


def collect():
    problems, rows, undescribed = [], [], []
    dirs = sorted(p.name for p in ROOT.iterdir() if p.is_dir() and not p.name.startswith((".", "_")))
    for name in dirs:
        if name in SKIP:
            continue
        if name in FROZEN:
            rows.append(dict(FROZEN[name]))
            continue
        yml = ROOT / name / "bench.yaml"
        if not yml.is_file():
            undescribed.append(name)
            continue
        d = parse_yaml(yml)
        for key in REQUIRED:
            if not d.get(key):
                problems.append(f"{name}/bench.yaml: missing '{key}'")
        if d.get("name") and d["name"] != name:
            problems.append(f"{name}/bench.yaml: name '{d['name']}' does not match the folder")
        if d.get("cluster") not in CLUSTER_KEYS:
            problems.append(f"{name}/bench.yaml: cluster '{d.get('cluster')}' is not one of {sorted(CLUSTER_KEYS)}")
            d["cluster"] = None
        if d.get("status") and d["status"] not in STATUSES:
            problems.append(f"{name}/bench.yaml: status '{d['status']}' is not one of {sorted(STATUSES)}")
        if d.get("claim_kind") and d["claim_kind"] not in CLAIM_KINDS:
            problems.append(f"{name}/bench.yaml: claim_kind '{d['claim_kind']}' is not one of {sorted(CLAIM_KINDS)}")
        if d.get("verdict") and d["verdict"] not in VERDICTS:
            problems.append(f"{name}/bench.yaml: verdict '{d['verdict']}' is not one of {sorted(VERDICTS)}")
        for key in ("prereg", "results"):
            for part in [p.strip() for p in d.get(key, "").split(";") if p.strip()]:
                if part.lower() == "none" or part.startswith(("http://", "https://")):
                    continue
                if not is_path(part):
                    problems.append(f"{name}/bench.yaml: {key} entry '{part}' is not a path (put annotations in a # comment line)")
                    continue
                rel = part.removeprefix("./")
                if rel.startswith(name + "/"):
                    rel = rel[len(name) + 1:]
                if not (ROOT / name / rel).exists():
                    problems.append(f"{name}/bench.yaml: {key} entry '{part}' does not exist under {name}/")
        d["name"] = name
        if d["cluster"] is None:
            undescribed.append(name)
            continue
        rows.append(d)
    return rows, undescribed, problems


def render(rows, undescribed):
    header = "| bench | what it measures | status | tier | claim kind | pre-registration | results |\n|---|---|---|---|---|---|---|"
    total = len(rows) + len(undescribed)
    status_counts = {}
    for r in rows:
        status_counts[r.get("status", "?")] = status_counts.get(r.get("status", "?"), 0) + 1
    if undescribed:
        status_counts["not yet described"] = len(undescribed)
    summary = ", ".join(f"{n} {s}" for s, n in sorted(status_counts.items(), key=lambda kv: (-kv[1], kv[0])))
    lines = [START, "", f"{total} rows: {summary}.", ""]
    for key, heading in CLUSTERS:
        group = sorted((r for r in rows if r["cluster"] == key), key=lambda r: r["name"])
        if not group:
            continue
        lines += [f"### {heading} ({len(group)})", "", header]
        for r in group:
            n = r["name"]
            lines.append(
                f"| [`{n}/`]({n}/) | {cell(r.get('title', ''))} | {cell(r.get('status', ''))} | "
                f"{cell(norm_tier(r.get('tier', '')))} | {cell(r.get('claim_kind', ''))} | "
                f"{link_list(n, r.get('prereg', 'none'))} | {link_list(n, r.get('results', 'none'))} |"
            )
        lines.append("")
    if undescribed:
        lines += [f"### Not yet described ({len(undescribed)})", "",
                  "These folders have no valid `bench.yaml` yet, so the index cannot say what they measure or how far to trust them. Read the folder itself before citing anything in it.", "",
                  header]
        for n in sorted(undescribed):
            lines.append(f"| [`{n}/`]({n}/) | {NOT_DESCRIBED} | ? | ? | ? | ? | ? |")
        lines.append("")
    lines.append(END)
    return "\n".join(lines), total


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--expect", type=int, default=81, help="rows the index must contain (default 81)")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if README.md would change")
    ap.add_argument("--strict", action="store_true", help="treat bench.yaml contract problems as fatal")
    args = ap.parse_args()

    rows, undescribed, problems = collect()
    for p in problems:
        print(f"warning: {p}", file=sys.stderr)
    if problems and args.strict:
        return 3

    block, total = render(rows, undescribed)
    if total != args.expect:
        print(f"error: index has {total} rows, expected {args.expect}; README.md not written", file=sys.stderr)
        return 1

    text = README.read_text(encoding="utf-8")
    i, j = text.find(START), text.find(END)
    if i < 0 or j < 0 or j < i:
        print("error: README.md is missing the BENCH-INDEX marker comments", file=sys.stderr)
        return 2
    new = text[:i] + block + text[j + len(END):]
    if args.check:
        if new != text:
            print("README.md bench index is out of date; run scripts/bench_index.py", file=sys.stderr)
            return 1
        print(f"README.md bench index is current ({total} rows)")
        return 0
    if new != text:
        README.write_text(new, encoding="utf-8")
    print(f"wrote {total} rows ({len(rows)} described, {len(undescribed)} not yet described)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
